import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const SRC_ROOT = path.join(ROOT, "assets", "originals");
const OUT_ROOT = path.join(ROOT, "public", "images");
const MANIFEST_PATH = path.join(ROOT, "src", "data", "image-manifest.generated.ts");

const PORTRAIT_DIRS = new Set([
  "doctors",
  "mental-health",
  "physiotherapy",
  "allied-health",
  "reception",
]);

function decodeUncompressed24BitBmp(buffer) {
  if (buffer.toString("ascii", 0, 2) !== "BM") {
    throw new Error("Unsupported BMP signature");
  }
  const pixelOffset = buffer.readUInt32LE(10);
  const width = buffer.readInt32LE(18);
  const rawHeight = buffer.readInt32LE(22);
  const bpp = buffer.readUInt16LE(28);
  const compression = buffer.readUInt32LE(30);
  if (bpp !== 24 || compression !== 0) {
    throw new Error(`Unsupported BMP format: bpp=${bpp}, compression=${compression}`);
  }
  const height = Math.abs(rawHeight);
  const bottomUp = rawHeight > 0;
  const rowStride = Math.ceil((width * 3) / 4) * 4;
  const rgb = Buffer.alloc(width * height * 3);

  for (let y = 0; y < height; y++) {
    const srcRow = bottomUp ? height - 1 - y : y;
    const srcStart = pixelOffset + srcRow * rowStride;
    const dstStart = y * width * 3;
    for (let x = 0; x < width; x++) {
      const s = srcStart + x * 3;
      const d = dstStart + x * 3;
      rgb[d] = buffer[s + 2];     // R
      rgb[d + 1] = buffer[s + 1]; // G
      rgb[d + 2] = buffer[s];     // B
    }
  }
  return { data: rgb, width, height, channels: 3 };
}

function walkFiles(dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walkFiles(full));
    } else if (!entry.name.startsWith(".")) {
      results.push(full);
    }
  }
  return results.sort();
}

async function run() {
  fs.rmSync(OUT_ROOT, { recursive: true, force: true });
  fs.mkdirSync(OUT_ROOT, { recursive: true });
  const files = walkFiles(SRC_ROOT);
  const manifest = {};

  for (const filePath of files) {
    const rel = path.relative(SRC_ROOT, filePath);
    const dirName = path.dirname(rel);
    const ext = path.extname(rel).toLowerCase();
    const base = path.basename(rel, ext);
    const key = `${dirName}/${base}`.replace(/\\/g, "/");
    const outDir = path.join(OUT_ROOT, dirName);
    fs.mkdirSync(outDir, { recursive: true });

    const sourceBytes = fs.readFileSync(filePath);
    const hash = crypto.createHash("sha256").update(sourceBytes).digest("hex").slice(0, 8);

    let pipeline;
    if (ext === ".bmp") {
      const raw = decodeUncompressed24BitBmp(sourceBytes);
      pipeline = sharp(raw.data, {
        raw: { width: raw.width, height: raw.height, channels: raw.channels },
      });
    } else {
      pipeline = sharp(filePath).rotate();
    }

    const meta = await pipeline.metadata();
    const maxWidth = PORTRAIT_DIRS.has(dirName) ? 720 : 1280;
    const targetWidth = meta.width && meta.width > maxWidth ? maxWidth : meta.width;

    const basePipe = pipeline
      .clone()
      .resize({ width: targetWidth, withoutEnlargement: true });

    const hashedKey = `${key}.${hash}`;
    const jpgPath = path.join(outDir, `${base}.${hash}.jpg`);
    const stableJpgPath = path.join(outDir, `${base}.jpg`);
    const webpPath = path.join(outDir, `${base}.${hash}.webp`);
    const avifPath = path.join(outDir, `${base}.${hash}.avif`);

    const jpgInfo = await basePipe
      .clone()
      .jpeg({ quality: 86, mozjpeg: true, progressive: true })
      .toFile(jpgPath);

    fs.copyFileSync(jpgPath, stableJpgPath);

    await basePipe
      .clone()
      .webp({ quality: 82 })
      .toFile(webpPath);

    await basePipe
      .clone()
      .avif({ quality: 62, effort: 5 })
      .toFile(avifPath);

    manifest[key] = {
      avif: `/images/${hashedKey}.avif`,
      webp: `/images/${hashedKey}.webp`,
      jpg: `/images/${hashedKey}.jpg`,
      width: jpgInfo.width,
      height: jpgInfo.height,
    };

    const origSize = fs.statSync(filePath).size;
    const webpSize = fs.statSync(webpPath).size;
    const avifSize = fs.statSync(avifPath).size;
    console.log(
      `[img] ${key}: ${jpgInfo.width}x${jpgInfo.height} | orig=${Math.round(origSize / 1024)}KB -> jpg=${Math.round(jpgInfo.size / 1024)}KB webp=${Math.round(webpSize / 1024)}KB avif=${Math.round(avifSize / 1024)}KB`
    );
  }

  fs.mkdirSync(path.dirname(MANIFEST_PATH), { recursive: true });
  const ts = `// Auto-generated by scripts/optimize-images.mjs — do not edit manually.\nexport interface OptimizedImageEntry {\n  avif: string;\n  webp: string;\n  jpg: string;\n  width: number;\n  height: number;\n}\n\nexport const IMAGE_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, OptimizedImageEntry>;\n\nexport type ImageAssetKey = keyof typeof IMAGE_MANIFEST;\n`;
  fs.writeFileSync(MANIFEST_PATH, ts, "utf8");
  console.log(`\nOptimized ${Object.keys(manifest).length} images and wrote manifest.`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
